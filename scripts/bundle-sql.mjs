// Joins the migrations into one file you can paste into the Supabase SQL editor.
import { readFileSync, writeFileSync } from "node:fs";
const files = ["0001_schema.sql", "0002_functions.sql", "0003_security.sql", "0004_pin_login.sql"];
const out = files.map((f) => `-- ===== ${f} =====\n${readFileSync(new URL(`../supabase/migrations/${f}`, import.meta.url), "utf8")}`).join("\n");
writeFileSync(new URL("../supabase/setup.sql", import.meta.url), `-- Neksus Dine: complete database setup (generated by "npm run sql:bundle", do not edit by hand)\n\n${out}`);
console.log("supabase/setup.sql written");
